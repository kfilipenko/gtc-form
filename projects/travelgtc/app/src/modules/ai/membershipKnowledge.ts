export function attachMembershipDocumentLink(question: string, answer: string): string {
  if (!isMembershipKnowledgeQuestion(question)) {
    return answer;
  }
  if (isDialogueFirstQuestion(question)) {
    return stripAutoDocumentLinks(answer);
  }
  const answerWithoutDocuments = stripAutoDocumentLinks(answer);
  if (isPairModelPresentationRequest(question)) {
    const fileRequested = /\b(pdf|файл|скачать|загрузить)\b/i.test(question);
    const link = fileRequested ? TRAVELGTC_PAIR_MODEL_PDF_URL : TRAVELGTC_PAIR_MODEL_PAGE_URL;
    const label = fileRequested ? 'PDF модели для пары на 24 месяца' : 'Модель для пары на 24 месяца';
    return `${answerWithoutDocuments}\n\n📊 ${label}: ${link}`;
  }
  if (!shouldAttachMembershipDocuments(question)) {
    return shouldOfferDocumentChoice(question, answerWithoutDocuments)
      ? appendDocumentChoiceOffer(answerWithoutDocuments)
      : answerWithoutDocuments;
  }
  if (answerWithoutDocuments.includes(MEMBERSHIP_KNOWLEDGE_DOCUMENT_URL)) {
    return answerWithoutDocuments;
  }

  return `${answerWithoutDocuments}\n\n📄 Рабочая таблица TravelGTC: ${MEMBERSHIP_KNOWLEDGE_DOCUMENT_URL}\nОфициальный Membership Benefits PDF: ${OFFICIAL_MEMBERSHIP_BENEFITS_URL}`;
}

function stripAutoDocumentLinks(answer: string): string {
  return answer
    .split('\n')
    .filter((line) => {
      const compact = line.trim();
      return (
        !/MembershipBenefits-RU|MembershipBenefits-EN|TravelGTC_Membership_Model_Presentation|membership-model\/|mwracademy\.com|FAQ MWR Life|Документ для проверки|Официальный PDF/i.test(
          compact,
        ) && compact !== '📄'
      );
    })
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function isPairModelPresentationRequest(question: string): boolean {
  const compact = question.replace(/\s+/g, ' ').trim();
  const pairContext = /(пар[аы]|вдво[её]м|семь[её]й|партн[её]р|совместн)/i.test(compact);
  const presentationIntent = /(модель|расч[её]т|презентац|слайд|файл)/i.test(compact);
  return pairContext && presentationIntent;
}

function shouldAttachMembershipDocuments(question: string): boolean {
  const compact = question.replace(/\s+/g, ' ').trim();
  if (
    /(почитал|прочитал|изучил|посмотрел|ознакомил[а-яё]*)\s+[^.!?]{0,80}(документ|pdf|файл|таблиц|презентац)/i.test(
      compact,
    ) &&
    /(зарегистр|регистрац|купить|оплат|ссылк|следующий шаг|официальн)/i.test(compact)
  ) {
    return false;
  }
  const explicitSendDocumentIntent =
    /(дай|дайте|пришли|пришлите|скинь|скиньте|отправь|отправьте|покажи|покажите|открой|откройте|хочу|нужен|нужна|нужно|да|давай|можно)\s+[^.!?]{0,80}(документ|pdf|файл|таблиц|презентац|ссылк|официальн|faq)/i.test(
      compact,
    ) ||
    /(документ|pdf|файл|таблиц|презентац|ссылк|faq)\s+[^.!?]{0,80}(дай|дайте|пришли|пришлите|скинь|скиньте|отправь|отправьте|покажи|покажите|открой|откройте|хочу|нужен|нужна|нужно|да|давай|можно)/i.test(
      compact,
    );
  return explicitSendDocumentIntent;
}

