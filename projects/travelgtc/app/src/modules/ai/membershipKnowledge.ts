export function isDialogueFirstQuestion(question: string): boolean {
  const userQuestion = question.includes('Сообщение пользователя:')
    ? question.split('Сообщение пользователя:').at(-1)?.trim() || question.trim()
    : question.trim();
  return /^(?:Мы путешествуем семь[её]й|Хочу посмотреть модель для пары|Я хочу путешествовать чаще\.|У меня есть группа|Хочу понять Elite \+ Turbo|Хочу создать business-направление|Я готов зарегистрироваться\.)/i.test(
    userQuestion,
  );
}

